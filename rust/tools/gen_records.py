#!/usr/bin/env python3
"""Generate Rust record types from copybooks (via copybook.py JSON).

Usage: gen_records.py <out.rs> <copybook>...
"""
import json, re, subprocess, sys, os

HERE = os.path.dirname(os.path.abspath(__file__))
KW = {"type", "match", "ref", "move", "use", "mod", "fn", "loop", "self", "box"}


def snake(n):
    s = n.lower().replace("-", "_")
    return s + "_" if s in KW else s


def camel(n):
    return "".join(p.capitalize() for p in n.lower().split("-"))


def lit(v, length):
    """Translate a VALUE clause into the byte content of an item."""
    v = v.strip()
    up = v.upper()
    if up in ("SPACE", "SPACES"):
        return b" " * length
    if up in ("ZERO", "ZEROS", "ZEROES"):
        return None  # numeric zero handled by caller
    if up in ("LOW-VALUE", "LOW-VALUES"):
        return b"\0" * length
    m = re.match(r"ALL\s+'(.*)'$", v, re.S)
    if m:
        s = m.group(1).encode()
        return (s * length)[:length]
    m = re.match(r"'(.*)'$", v, re.S) or re.match(r'"(.*)"$', v, re.S)
    if m:
        s = m.group(1).replace("''", "'").encode()
        return (s + b" " * length)[:length]
    return None


def main():
    out, cpys = sys.argv[1], sys.argv[2:]
    data = json.loads(subprocess.check_output([sys.executable, os.path.join(HERE, "copybook.py"), "json", *cpys]))
    w = ["// @generated by tools/gen_records.py from the CardDemo copybooks. Do not edit.",
         "#![allow(clippy::all, dead_code)]",
         "use crate::numeric::{Dec, Pic, Usage};", "use crate::field;", ""]
    for rec, info in data.items():
        if rec in seen:
            continue
        seen.add(rec)
        name = camel(rec)
        L = info["len"]
        fields = info["fields"]
        w.append(f"/// `{rec}` from `{os.path.basename(info['file'])}` ({L} bytes).")
        w.append("#[derive(Clone, PartialEq, Eq, Debug)]")
        w.append(f"pub struct {name} {{ pub buf: [u8; {L}] }}")
        w.append(f"impl Default for {name} {{ fn default() -> Self {{ Self::new() }} }}")
        w.append(f"impl {name} {{")
        w.append(f"    pub const LEN: usize = {L};")
        # occurs stack: per field, list of (stride, count) of ancestors incl. itself
        stack = []  # (depth, stride, count)
        init = []
        used = set()
        for f in fields:
            while stack and stack[-1][0] >= f["depth"]:
                stack.pop()
            occ = [(s, c) for _, s, c in stack]
            if f["occurs"] > 1:
                occ.append((f["len"], f["occurs"]))
                stack.append((f["depth"], f["len"], f["occurs"]))
            nm = f["name"]
            if nm == "FILLER":
                if f["value"] is not None and not f["group"]:
                    init.append((f, occ))
                continue
            fn = snake(nm)
            if fn in used:
                fn = f"{fn}_{f['offset']}"
            used.add(fn)
            params = "".join(f", i{k}: usize" for k in range(len(occ)))
            off = str(f["offset"]) + "".join(f" + (i{k} - 1) * {s}" for k, (s, _) in enumerate(occ))
            ln = f["len"]
            rng = f"{off}..{off} + {ln}"
            w.append(f"    pub fn {fn}(&self{params}) -> &[u8] {{ &self.buf[{rng}] }}")
            w.append(f"    pub fn set_{fn}(&mut self{params}, v: &[u8]) {{ crate::text::mv(&mut self.buf[{rng}], v) }}")
            if f["kind"] == "9":
                usage = {"COMP-3": "Comp3", "COMP": "Binary", "BINARY": "Binary", "COMP-4": "Binary",
                         "COMP-5": "Binary", "PACKED-DECIMAL": "Comp3"}.get(f["usage"], "Display")
                pic = f"Pic {{ digits: {f['digits']}, scale: {f['scale']}, signed: {str(bool(f['signed'])).lower()}, usage: Usage::{usage} }}"
                w.append(f"    pub const {fn.upper().rstrip('_')}_PIC: Pic = {pic};")
                w.append(f"    pub fn {fn}_n(&self{params}) -> Dec {{ field::get_n(&self.buf[{rng}], Self::{fn.upper().rstrip('_')}_PIC) }}")
                w.append(f"    pub fn set_{fn}_n(&mut self{params}, v: Dec) {{ field::set_n(&mut self.buf[{rng}], Self::{fn.upper().rstrip('_')}_PIC, v) }}")
            elif f["kind"] == "E":
                w.append(f"    pub fn set_{fn}_n(&mut self{params}, v: Dec) {{ field::set_edited(&mut self.buf[{rng}], {f['pic']!r:}, v) }}".replace("'", '"'))
            if f["value"] is not None and not f["group"]:
                init.append((f, occ))
        # constructor implementing INITIALIZE + VALUE clauses
        w.append("    /// A new record as allocated by the program: VALUE clauses applied,")
        w.append("    /// otherwise INITIALIZE semantics (alphanumeric = spaces, numeric = zero).")
        w.append("    pub fn new() -> Self {")
        w.append(f"        let mut r = Self {{ buf: [b' '; {L}] }};")
        w.append("        r.initialize();")
        for f, occ in init:
            if occ:
                continue
            b = lit(f["value"], f["len"])
            off, ln = f["offset"], f["len"]
            if b is not None:
                w.append(f"        r.buf[{off}..{off + ln}].copy_from_slice(b{json.dumps(b.decode('latin-1'))});")
            elif f["kind"] == "9":
                v = f["value"].upper()
                num = "0" if v.startswith("ZERO") else v
                usage = {"COMP-3": "Comp3", "COMP": "Binary", "BINARY": "Binary"}.get(f["usage"], "Display")
                w.append(f"        field::set_n(&mut r.buf[{off}..{off + ln}], Pic {{ digits: {f['digits']}, scale: {f['scale']}, signed: {str(bool(f['signed'])).lower()}, usage: Usage::{usage} }}, \"{num}\".parse().unwrap());")
        w.append("        r")
        w.append("    }")
        # INITIALIZE (IBM semantics): elementary items get spaces (alphanumeric) or zero (numeric);
        # FILLER items and items under a REDEFINES are left untouched.
        w.append("    /// COBOL INITIALIZE: alphanumeric items to spaces, numeric items to zero;")
        w.append("    /// FILLER and REDEFINES items keep their contents.")
        w.append("    pub fn initialize(&mut self) {")
        stack = []
        redef = []  # depths of REDEFINES groups we are inside
        for f in fields:
            while stack and stack[-1][0] >= f["depth"]:
                stack.pop()
            while redef and redef[-1] >= f["depth"]:
                redef.pop()
            occ = [(s, c) for _, s, c in stack]
            if f["occurs"] > 1:
                occ.append((f["len"], f["occurs"]))
                stack.append((f["depth"], f["len"], f["occurs"]))
            if f["redefines"]:
                redef.append(f["depth"])
            if redef or f["group"] or f["name"] == "FILLER":
                continue
            loops = ""
            close = ""
            off = str(f["offset"])
            for k, (s, c) in enumerate(occ):
                loops += f"for i{k} in 1..={c} {{ "
                close += " }"
                off += f" + (i{k} - 1) * {s}"
            if f["kind"] != "9":
                w.append(f"        {loops}self.buf[{off}..{off} + {f['len']}].fill(b' ');{close}")
                continue
            usage = {"COMP-3": "Comp3", "COMP": "Binary", "BINARY": "Binary"}.get(f["usage"], "Display")
            pic = f"Pic {{ digits: {f['digits']}, scale: {f['scale']}, signed: {str(bool(f['signed'])).lower()}, usage: Usage::{usage} }}"
            w.append(f"        {loops}field::set_n(&mut self.buf[{off}..{off} + {f['len']}], {pic}, Dec::ZERO);{close}")
        w.append("    }")
        w.append(f"    pub fn from_bytes(b: &[u8]) -> Self {{ let mut r = Self {{ buf: [b' '; {L}] }}; crate::text::mv(&mut r.buf, b); r }}")
        w.append("}")
        w.append("")
    open(out, "w").write("\n".join(w) + "\n")


seen = set()
if __name__ == "__main__":
    main()
